-- ----------------------------------------------------------------------------
-- 1. Seller-tracker + offer-receipt + closing-date + inherited-home
--    columns on the existing leads table. The table already exists
--    (see lib/leads.ts); this only ADDS what Slice 125 needs. No
--    RLS change: the leads table's existing sealed-office policies
--    already fence every row to its owner, and the seller sees
--    their own row only through the token-checked /api/track route.
--      tracker_token          — unguessable uuid, generated by the
--                                database at insert; the seller's
--                                private tracking link is
--                                /track/<token>. Existing rows get
--                                a token on this run, so the
--                                wholesaler can share a link for
--                                any seller-page lead.
--      seller_status          — the seller-facing progress:
--                                received / reviewed / offer_made /
--                                closing_scheduled / closed. This
--                                is NOT the wholesaler's internal
--                                CRM status (new/contacted/…).
--      preferred_closing_date — the day the seller picked in the
--                                form; the offer follows it.
--      offer_amount           — the wholesaler's own offer, in
--                                dollars. The receipt shows only
--                                when this is set.
--      offer_comp_low/high    — the comparable-sales range the
--                                wholesaler entered. A range, never
--                                a fabricated single comp.
--      offer_repairs          — the repair estimate the wholesaler
--                                entered.
--      offer_resale_costs     — the resale costs the wholesaler
--                                entered.
--      offer_note             — a short note shown on the receipt.
--      inherited_home         — the seller used the inherited-home
--                                fast lane.
--      estate_role            — Personal representative / Trustee /
--                                Other (stored in English; the form
--                                shows translated labels).
--      letters_issued         — Yes / No / Not yet / Not sure.
--      court_approval         — Yes / No / Not sure.
--      estate_notes           — free text about the estate.
--    Any receipt piece the wholesaler leaves blank reads "not
--    provided" on the seller's receipt — nothing is invented.
-- ----------------------------------------------------------------------------
