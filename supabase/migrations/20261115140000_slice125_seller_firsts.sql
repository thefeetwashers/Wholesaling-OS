-- ----------------------------------------------------------------------------
-- 3. Private 'storefront-videos' Storage bucket + policies.
--    Idempotent: the bucket insert is ON CONFLICT DO NOTHING and
--    the policies are dropped before creation. A wholesaler
--    uploads only under their own user id (<wholesaler_id>/…);
--    they read only their own video; the operator reads all. No
--    public access: the bucket is private and the public page
--    plays a video only through a short-lived signed URL minted
--    by /api/storefront-video for that wholesaler's slug. There
--    is no public listing of videos.
--    NOTE (owner): after applying, confirm in the dashboard that
--    the bucket 'storefront-videos' exists and is private.
-- ----------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('storefront-videos', 'storefront-videos', false)
on conflict (id) do nothing;

drop policy if exists "wholesaler uploads own storefront video" on storage.objects;
create policy "wholesaler uploads own storefront video"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'storefront-videos'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "wholesaler reads own storefront video" on storage.objects;
create policy "wholesaler reads own storefront video"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'storefront-videos'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "wholesaler deletes own storefront video" on storage.objects;
create policy "wholesaler deletes own storefront video"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'storefront-videos'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "operator reads all storefront videos" on storage.objects;
create policy "operator reads all storefront videos"
  on storage.objects
  for select
  to authenticated
  using (
    bucket_id = 'storefront-videos'
    and public.is_operator()
  );

-- ----------------------------------------------------------------------------
-- 4. complete_seller_lead — step 2, extended. The Slice 124
--    version is dropped first (a new signature is a new overload
--    in Postgres, so dropping keeps exactly one function) and
--    recreated with the same guards — slug resolves to an enabled,
--    unsuspended seller page; the lead belongs to that page's
--    owner, source 'Seller landing page', created within the last
--    2 hours — plus the Slice 125 step-2 fields: the closing day
--    the seller picked and the inherited-home fast-lane answers.
--    Every new parameter has a default, so a call with only the
--    original eleven behaves identically to the original.
-- ----------------------------------------------------------------------------
drop function if exists public.complete_seller_lead(text, text, text, text, text, text, text, text, text, numeric, text);

create or replace function public.complete_seller_lead(
  p_slug text,
  p_lead_id text,
  p_city text,
  p_state text,
  p_zip text,
  p_property_type text,
  p_condition text,
  p_occupancy text,
  p_timeline text,
  p_asking_price numeric,
  p_notes text,
  p_preferred_closing_date date default null,
  p_inherited_home boolean default false,
  p_estate_role text default null,
  p_letters_issued text default null,
  p_court_approval text default null,
  p_estate_notes text default null
)
returns boolean
language plpgsql
security definer
as $$
declare
  v_owner uuid;
  v_lead_owner uuid;
  v_source text;
  v_created timestamptz;
begin
  if p_lead_id is null or p_lead_id = '' then
    return false;
  end if;
  select id into v_owner
    from public.profiles
   where public_slug = lower(trim(p_slug))
     and seller_page_enabled = true
     and admin_suspended = false;
  if v_owner is null then
    return false;
  end if;
  select owner_id, list_source, created_at
    into v_lead_owner, v_source, v_created
    from public.leads
   where id = p_lead_id::uuid;
  if v_lead_owner is null or v_lead_owner <> v_owner then
    return false;
  end if;
  if v_source <> 'Seller landing page' then
    return false;
  end if;
  if now() - v_created > interval '2 hours' then
    return false;
  end if;
  update public.leads
     set city = nullif(trim(coalesce(p_city, '')), ''),
         state = nullif(trim(coalesce(p_state, '')), ''),
         zip = nullif(trim(coalesce(p_zip, '')), ''),
         property_type = nullif(trim(coalesce(p_property_type, '')), ''),
         condition = nullif(trim(coalesce(p_condition, '')), ''),
         occupancy = nullif(trim(coalesce(p_occupancy, '')), ''),
         timeline = nullif(trim(coalesce(p_timeline, '')), ''),
         asking_price = p_asking_price,
         notes = p_notes,
         is_partial = false,
         preferred_closing_date = p_preferred_closing_date,
         inherited_home = coalesce(p_inherited_home, false),
         estate_role = case when coalesce(p_inherited_home, false) then nullif(trim(coalesce(p_estate_role, '')), '') else null end,
         letters_issued = case when coalesce(p_inherited_home, false) then nullif(trim(coalesce(p_letters_issued, '')), '') else null end,
         court_approval = case when coalesce(p_inherited_home, false) then nullif(trim(coalesce(p_court_approval, '')), '') else null end,
         estate_notes = case when coalesce(p_inherited_home, false) then nullif(trim(coalesce(p_estate_notes, '')), '') else null end
   where id = p_lead_id::uuid;
  return found;
end;
$$;

